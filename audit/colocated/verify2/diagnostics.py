ROOT = Path(".").resolve()
rr = records()
val_ids = [i for i, r in enumerate(rr) if r['split'] == 'val']
features = np.load(rt.OLD / "B2_448_features.npy", mmap_mode='r')

def get_soft_scores(z, centers, temp, cluster):
    d = distances(z.reshape(-1, 70), centers)
    weights = np.exp(-(d - d.min(1, keepdims=True)) / temp)
    weights /= weights.sum(1, keepdims=True)
    return weights[:, cluster]

res = {}
# Frozen features (assuming 768-D K=8 centers are in OLD or archive, wait, we don't have the exact frozen centers, or do we?
# The prompt says "frozen features". In previous steps, frozen centers were generated by KMeans on the frozen features.
# I can just fit KMeans on frozen features here.
from sklearn.cluster import KMeans
train_ids = [i for i, r in enumerate(rr) if r['split'] == 'train']
sample_frozen = np.zeros((len(train_ids)*784, 768), dtype=np.float32)
for j, i in enumerate(train_ids):
    sample_frozen[j*784:(j+1)*784] = features[i]
    
km_frozen = KMeans(n_clusters=8, random_state=0, n_init=3, max_iter=100, tol=1e-4, algorithm='lloyd').fit(sample_frozen)
centers_frozen = km_frozen.cluster_centers_
d_frozen = distances(sample_frozen, centers_frozen)
two_frozen = np.partition(d_frozen, 1, axis=1)[:, :2]
temp_frozen = max(float(np.median(two_frozen[:,1]-two_frozen[:,0])/np.log(4)), 1e-6)

print(f"Frozen Temp: {temp_frozen}")

soft_frozen = []
for i in val_ids:
    z_f = features[i].reshape(-1, 768)
    d = distances(z_f, centers_frozen)
    weights = np.exp(-(d - d.min(1, keepdims=True)) / temp_frozen)
    weights /= weights.sum(1, keepdims=True)
    # just pick max cluster to approximate distribution of max probabilities
    soft_frozen.extend(weights.max(1))
    
# Trained codes (Seed 0, C448)
ckpt = torch.load("experiments/stego_colocated/C448/stage2/checkpoints/seed0/final.pt", map_location='cpu', weights_only=True)
model = StegoHead().eval().requires_grad_(False)
model.load_state_dict(ckpt['state_dict'])

centers_trained = np.load("experiments/stego_colocated/C448/stage2/predictions/seed0/centers.npy")
fit_trained = json.loads(Path("experiments/stego_colocated/C448/stage2/predictions/seed0/fit.json").read_text())
temp_trained = fit_trained["temperature"]
print(f"Trained Temp (C448 Seed 0): {temp_trained}")

soft_trained = []
for i in val_ids:
    f = torch.from_numpy(np.array(features[i])).reshape(28,28,768).permute(2,0,1)[None]
    with torch.no_grad():
        z_t = model.embed(f)[0].permute(1,2,0).contiguous().numpy()
    z_t = z_t.reshape(-1, 70)
    d = distances(z_t, centers_trained)
    weights = np.exp(-(d - d.min(1, keepdims=True)) / temp_trained)
    weights /= weights.sum(1, keepdims=True)
    soft_trained.extend(weights.max(1))
    
q_f = np.percentile(soft_frozen, [0, 25, 50, 75, 100])
q_t = np.percentile(soft_trained, [0, 25, 50, 75, 100])

print(f"Frozen Soft Score Quantiles (0, 25, 50, 75, 100): {q_f}")
print(f"Trained Soft Score Quantiles (0, 25, 50, 75, 100): {q_t}")
