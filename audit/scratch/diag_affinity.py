"""Measure real ContrastiveCorrelationLoss.helper affinities with restored mean; no formula clone."""
from diag_common import *
from modules import ContrastiveCorrelationLoss,sample
import argparse
p=argparse.ArgumentParser();p.add_argument('--block',type=int,required=True);p.add_argument('--center',type=int,choices=[0,1],required=True);args=p.parse_args()
plan=json.loads((OUT/'plan.json').read_text());rows=plan['train'];n=len(rows)
a=np.load(OUT/f'train_block{args.block}.npy',mmap_mode='r')
mean=np.asarray(a).mean(axis=(0,1),dtype=np.float64).astype(np.float32)
f=torch.from_numpy(np.array(a)).transpose(1,2).reshape(n,768,14,14)
if args.center:f=f-torch.from_numpy(mean)[None,:,None,None]
# Real training order: sample first, then helper's channel normalization and restored-mean centering.
# The helper gets scalar-one codes and shift0, so cd==1 exactly and returned loss == -affinity.
loss=ContrastiveCorrelationLoss(cfg());assert cfg().pointwise and not cfg().stabalize
rng=np.random.default_rng(SEED)
pairs={'intra':[(i,i) for i in range(n)],'knn':[(x,y) for x,y,_ in plan['knn_pairs']],
       'random':[(i,int(rng.choice([j for j in range(n) if j!=i]))) for i in range(n)],
       'cross_patient':[(i,int(rng.choice([j for j in range(n) if rows[j]['patient_id']!=rows[i]['patient_id']]))) for i in range(n)]}
values={}
with torch.no_grad():
 for name,edges in pairs.items():
    torch.manual_seed(SEED)
    c1=torch.rand(len(edges),11,11,2)*2-1;c2=torch.rand(len(edges),11,11,2)*2-1
    parts=[]
    for start in range(0,len(edges),16):
        e=edges[start:start+16];fa=sample(f[[i for i,j in e]],c1[start:start+len(e)])
        fb=fa if name=='intra' else sample(f[[j for i,j in e]],c2[start:start+len(e)])
        ones=torch.ones(len(e),1,11,11)
        negative_affinity,cd=loss.helper(fa,fb,ones,ones,0.0)
        assert torch.equal(cd,torch.ones_like(cd))
        parts.append((-negative_affinity).numpy().ravel())
    values[name]=np.concatenate(parts)
q=[5,25,50,75,90,95,99];shifts=[float(cfg().pos_intra_shift),float(cfg().pos_inter_shift),float(cfg().neg_inter_shift)]
summary={k:dict(image_pair_count=len(pairs[k]),patch_pair_count=len(v),mean_affinity=float(v.mean(dtype=np.float64)),quantiles=dict(zip(map(str,q),np.percentile(v,q).tolist())),attraction_current_intra_inter_neg=[float(np.mean(v>s)) for s in shifts]) for k,v in values.items()}
candidates=[]
for tail in [.20,.15,.10]:
    si=float(np.quantile(values['intra'],.25));sp=float(np.quantile(values['knn'],.25));sn=float(np.quantile(values['random'],1-tail))
    # Affinities come exclusively from the real helper above. Weighted constant-code loss
    # follows from its measured zero-shift loss and the shift's additive scalar effect.
    constant_loss=sum(float(w)*float((s-values[k]).mean(dtype=np.float64)) for k,s,w in [('intra',si,cfg().pos_intra_weight),('knn',sp,cfg().pos_inter_weight),('random',sn,cfg().neg_inter_weight)])
    candidates.append(dict(target_random_attraction=tail,shifts_intra_inter_neg=[si,sp,sn],constant_code_correspondence_loss=constant_loss,attraction={k:[float(np.mean(v>s)) for s in [si,sp,sn]] for k,v in values.items()}))
result=dict(script=__file__,block=args.block,mean_subtracted=bool(args.center),seed=SEED,current_shifts_intra_inter_neg=shifts,normalization='raw normalized-block tokens, optionally train-mean subtracted; actual project sample then helper normalization/centering',quantiles=summary,candidates=candidates,heuristic='User-proposed starting heuristic, NOT Paper A: intra/inter shift at corresponding25th percentile; negative at random80th/85th/90th percentile. No labels used. Separate role-specific shifts do not prove feature distributions separable or training stable.',elapsed_seconds=elapsed())
dump(f'affinity_b{args.block}_c{args.center}.json',result)
print(json.dumps(dict(block=args.block,center=args.center,summary=summary,candidates=candidates,elapsed_seconds=elapsed()),indent=2))
with (ROOT/'audit/DIAG.md').open('a') as out:out.write(f'\nAffinity block{args.block}, centered{args.center}: `audit/scratch/diag/affinity_b{args.block}_c{args.center}.json` generated by `{__file__}`, elapsed{elapsed()}s.\n')
