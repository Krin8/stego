import guard,signal
signal.alarm(110)
import torch,numpy as np
from torch import nn
import torch.nn.functional as F
from scipy.optimize import linear_sum_assignment
from types import SimpleNamespace
torch.set_num_threads(2)
ns=guard.definitions('src/modules.py',['norm','tensor_correlation','sample','sample_nonzero_locations','ContrastiveCorrelationLoss','ClusterLookup','ContrastiveCRFLoss'],dict(torch=torch,nn=nn,F=F))
class Metric(nn.Module):
    def __init__(self,**kwargs):super().__init__()
    def add_state(self,name,default,**kwargs):setattr(self,name,default)
ms=guard.definitions('src/utils.py',['UnsupervisedMetrics'],dict(torch=torch,np=np,Metric=Metric,linear_sum_assignment=linear_sum_assignment))
out=[];torch.manual_seed(11)
cfg=SimpleNamespace(pointwise=True,zero_clamp=True,stabalize=False,feature_samples=2,neg_samples=2,use_salience=False,pos_intra_shift=.18,pos_inter_shift=.12,neg_inter_shift=.46)
lossfn=ns['ContrastiveCorrelationLoss'](cfg)
f=torch.randn(2,3,2,2,requires_grad=True);g=torch.randn(2,3,2,2,requires_grad=True)
c=torch.randn(2,4,2,2,requires_grad=True);d=torch.randn(2,4,2,2,requires_grad=True)
for name,fa,fb,ca,cb,shift in [('self',f,f,c,c,.18),('knn',f,g,c,d,.12),('rand',f,-g,c,d,.46)]:
    actual,_=lossfn.helper(fa,fb,ca,cb,shift)
    fd=torch.einsum('bch,bci->bhi',F.normalize(fa.flatten(2),dim=1),F.normalize(fb.flatten(2),dim=1))
    cd=torch.einsum('bch,bci->bhi',F.normalize(ca.flatten(2),dim=1),F.normalize(cb.flatten(2),dim=1))
    centered=fd-fd.mean(-1,keepdim=True)
    paper=-(centered-shift)*cd.clamp_min(0)
    ref=-(centered+fd.mean()-shift)*cd.clamp_min(0)
    out.append(f'{name}: actual={actual.mean().item():.8f} paper_mean={paper.mean().item():.8f} ref_mean={ref.mean().item():.8f} max_ref_error={(actual.reshape_as(ref)-ref).abs().max().item():.2g}')
    actual.mean().backward(retain_graph=True)
out.append(f'corr gradients backbone={f.grad} code_finite={bool(torch.isfinite(c.grad).all())}')
res=lossfn(f,g,None,None,c,d,-g,d)
total=.5*(.67*res[0]+.25*res[2]+.63*res[4].mean());total.backward()
out.append('forward weighted Eq5 branch finite='+str(bool(torch.isfinite(total)))+' shapes='+str([tuple(t.shape) for t in res]))
probe=ns['ClusterLookup'](2,2);probe.clusters.data.copy_(torch.eye(2))
x=torch.tensor([[[[1.,0.]],[[0.,1.]]]])
loss,p=probe(x,None);entropy=-(p.mean((0,2,3))*(p.mean((0,2,3))+1e-8).log()).sum()
out.append(f'cluster balanced: paper=-1 actual={loss.item():.8f} entropy_requires_grad={entropy.requires_grad} expected_extra_offset={-.5*np.log(2):.8f}')
metric=ms['UnsupervisedMetrics']('',2,2,True)
metric.stats=torch.tensor([[0,0],[0,0],[0,10],[90,0]])
metrics=metric.compute();mapped=metric.map_clusters(torch.arange(4))
out.append(f'Hungarian selected={metric.assignments} metric={metrics} actual_LUT={mapped.tolist()} required_LUT=[0,0,1,0]')
metric.stats=torch.tensor([[80,0],[0,10],[10,0],[0,0]])
out.append('extra-bin mIoU='+str(metric.compute())+' expected over 2 anatomical classes='+str(100*(80/90+1)/2))
img=torch.arange(16,dtype=torch.float32).reshape(1,1,4,4)
y,x=torch.meshgrid(torch.linspace(-1,1,4),torch.linspace(-1,1,4),indexing='ij')
coord=torch.stack([y,x],dim=-1).unsqueeze(0)
out.append('identity augmentation max error='+str(float((ns['sample'](img,coord)-img).abs().max())))
hf=coord.flip(2)
out.append('horizontal-flip alignment max error='+str(float((ns['sample'](img,hf)-img.flip(3)).abs().max()))+' sampled_equals_vertical_flip='+str(torch.allclose(ns['sample'](img,hf),img.flip(2))))
sal=torch.zeros(1,4,6);sal[0,3,5]=1
out.append('salience bottom-right coords='+str(ns['sample_nonzero_locations'](sal,[1,1,1,2]).flatten().tolist())+' required=[1,1]')
crf=ns['ContrastiveCRFLoss'](3,.5,.1,.05,10.,3.,0.)
guide=torch.zeros(1,3,1,1);code=torch.tensor([[[[1.]],[[0.]]]],requires_grad=True)
cv=crf(guide,code)
out.append(f'CRF same pixel expected=-13 actual={cv.mean().item()} shape={tuple(cv.shape)}')
out.append('reconstruction same/opposite cosine losses='+str([float(-(F.normalize(code,dim=1)*F.normalize(z,dim=1)).sum(1).mean()) for z in [code,-code]]))
lp=nn.Conv2d(2,2,1);det=code.detach();ce=nn.CrossEntropyLoss(weight=torch.tensor([1.,5.]))(lp(det),torch.ones(1,1,1,dtype=torch.long));ce.backward()
out.append('detached linear CE code grad='+str(code.grad)+' probe_grad='+str(lp.weight.grad is not None))
guard.record('Phase 4 numerical method and silent-failure evidence', '\n'.join(out))
